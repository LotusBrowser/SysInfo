    private sealed record Battery(string Name, string? Maker, string? Chemistry, string? Status, long? Percent,
                                  double? RuntimeMinutes, double? DesignMwh, double? FullMwh, long? Cycles);

    private static (List<Battery>, bool?) ReadPower()
    {
        var list = new List<Battery>();
        bool? ac = null;

        foreach (string d in Lx.Dirs("/sys/class/power_supply"))
        {
            string? type = Lx.Read(d + "/type");
            if (type == "Mains")
            {
                if (Lx.ReadLong(d + "/online") is { } online) ac = (ac ?? false) || online == 1;
                continue;
            }
            if (type != "Battery") continue;
            if (Lx.Read(d + "/scope") == "Device") continue; // wireless mouse / headset batteries

            string? tech = Lx.Read(d + "/technology");
            string? chem = tech switch
            {
                "Li-ion" => "Lithium-ion",
                "Li-poly" => "Lithium Polymer",
                "LiFe" => "Lithium Iron Phosphate",
                "NiMH" => "Nickel Metal Hydride",
                "NiCd" => "Nickel Cadmium",
                "Unknown" => null,
                _ => tech
            };

            string? statusRaw = Lx.Read(d + "/status");
            string? status = statusRaw switch
            {
                "Charging" => "Charging",
                "Discharging" => "Discharging",
                "Full" => "Fully charged",
                "Not charging" => "On AC power (not charging)",
                _ => null
            };

            double? runtime = null;
            if (statusRaw == "Discharging")
            {
                long? energyNow = Lx.ReadLong(d + "/energy_now"), powerNow = Lx.ReadLong(d + "/power_now");
                long? chargeNow = Lx.ReadLong(d + "/charge_now"), currentNow = Lx.ReadLong(d + "/current_now");
                if (energyNow is > 0 && powerNow is > 0) runtime = energyNow.Value / (double)powerNow.Value * 60;
                else if (chargeNow is > 0 && currentNow is > 0) runtime = chargeNow.Value / (double)currentNow.Value * 60;
                if (runtime is > 100_000) runtime = null;
            }

            list.Add(new Battery(
                Lx.Tidy(Lx.Read(d + "/model_name")) ?? Path.GetFileName(d),
                Lx.Tidy(Lx.Read(d + "/manufacturer")),
                chem, status,
                Lx.ReadLong(d + "/capacity"),
                runtime,
                EnergyMwh(d, "energy_full_design", "charge_full_design"),
                EnergyMwh(d, "energy_full", "charge_full"),
                Lx.ReadLong(d + "/cycle_count")));
        }
        return (list, ac);

        // sysfs reports energy in µWh, or charge in µAh (convert with voltage: µAh * µV / 1e9 = mWh)
        static double? EnergyMwh(string dir, string energyFile, string chargeFile)
        {
            if (Lx.ReadLong($"{dir}/{energyFile}") is > 0 and var e) return e / 1000.0;
            long? charge = Lx.ReadLong($"{dir}/{chargeFile}");
            long? volt = Lx.ReadLong(dir + "/voltage_min_design") ?? Lx.ReadLong(dir + "/voltage_now");
            return charge is > 0 && volt is > 0 ? charge.Value * (double)volt.Value / 1e9 : null;
        }
    }

