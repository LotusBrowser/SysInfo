        ["07"] = "Printer", ["08"] = "Mass Storage", ["09"] = "Hub", ["0a"] = "CDC Data", ["0b"] = "Smart Card",
        ["0d"] = "Content Security", ["0e"] = "Video / Camera", ["0f"] = "Personal Healthcare", ["10"] = "Audio/Video",
        ["11"] = "Billboard", ["dc"] = "Diagnostic", ["e0"] = "Wireless / Bluetooth", ["ef"] = "Miscellaneous",
        ["fe"] = "Application Specific", ["ff"] = "Vendor Specific"
    };

    private static List<object?[]> ReadUsbDevices()
    {
        var rows = new List<(string Cls, string Name, object?[] Row)>();

        // Names from the USB ID database, used when a device exposes no product string.
        var lsusb = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        bool lsusbLoaded = false;

        foreach (string dir in Lx.Dirs("/sys/bus/usb/devices"))
        {
            string dirName = Path.GetFileName(dir);
            if (!Regex.IsMatch(dirName, @"^\d+-\d+(\.\d+)*$")) continue; // real devices only, not root hubs or interfaces

            string? vid = Lx.Read(dir + "/idVendor"), pid = Lx.Read(dir + "/idProduct");
            if (vid is null || pid is null) continue;

            string? devClass = Lx.Read(dir + "/bDeviceClass");
            if (devClass == "09") continue; // hubs

            string? maker = Lx.Tidy(Lx.Read(dir + "/manufacturer"));
            string? prod = Lx.Tidy(Lx.Read(dir + "/product"));
            string name = prod is null ? "" : maker is not null && !prod.Contains(maker, StringComparison.OrdinalIgnoreCase) ? $"{maker} {prod}" : prod;
            if (name.Length == 0)
            {
                if (!lsusbLoaded)
                {
                    lsusbLoaded = true;
                    foreach (string l in (Lx.Run("lsusb", Array.Empty<string>(), 4000) ?? "").Split('\n'))
                    {
                        var m = Regex.Match(l, @"ID ([0-9a-fA-F]{4}):([0-9a-fA-F]{4})\s*(.*)$");
                        if (m.Success) lsusb[$"{m.Groups[1].Value}:{m.Groups[2].Value}"] = m.Groups[3].Value.Trim();
                    }
                }
                name = lsusb.GetValueOrDefault($"{vid}:{pid}") ?? "Unknown USB device";
            }

            // Composite devices declare their purpose per interface.
            string cls;
            if (devClass is null or "00" or "ef")
            {
                var ifaceClasses = Lx.Dirs("/sys/bus/usb/devices", dirName + ":*")
                    .Select(i => Lx.Read(i + "/bInterfaceClass"))
                    .Where(c => c is not null)
                    .Select(c => UsbClass.GetValueOrDefault(c!, "Other"))
                    .Distinct()
                    .Take(3);
                cls = string.Join(", ", ifaceClasses);
                if (cls.Length == 0) cls = devClass is null ? "Other" : UsbClass.GetValueOrDefault(devClass, "Other");
            }
            else cls = UsbClass.GetValueOrDefault(devClass, "Other");

            rows.Add((cls, name, new object?[] { cls, name, $"{vid}:{pid}" }));
        }
        return rows.OrderBy(r => r.Cls, StringComparer.OrdinalIgnoreCase).ThenBy(r => r.Name, StringComparer.OrdinalIgnoreCase).Select(r => r.Row).ToList();
    }

    // ------------------------------------------------------------------------------------------
    //  TPM
    // ------------------------------------------------------------------------------------------
    private sealed record TpmInfo(bool Present, string SpecVersion, string Manufacturer);

    private static TpmInfo ReadTpm()
    {
        const string root = "/sys/class/tpm/tpm0";
        if (!Directory.Exists(root)) return new TpmInfo(false, "-", "-");

        string spec = "-";
        if (Lx.Read(root + "/tpm_version_major") is { } major) spec = major + ".0";
        else if (File.Exists(root + "/device/caps")) spec = "1.2"; // only TPM 1.2 exposes "caps"

        // Manufacturer is only available through the TPM itself (tpm2-tools + access to /dev/tpmrm0).
        string manufacturer = "-";
        string? props = Lx.Run("tpm2_getcap", new[] { "properties-fixed" }, 4000);
        if (props is not null)
        {
            var m = Regex.Match(props, @"TPM2_PT_MANUFACTURER:\s*\r?\n\s*raw:\s*\S+\s*\r?\n\s*value:\s*""?([^""\r\n]+)""?");
            if (m.Success) manufacturer = m.Groups[1].Value.Trim();
        }
        return new TpmInfo(true, spec, manufacturer);
    }
