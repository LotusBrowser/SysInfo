    // ------------------------------------------------------------------------------------------
    //  GPU
    // ------------------------------------------------------------------------------------------
    private static List<object?[]> ReadGpus(string? kernel)
    {
        var rows = new List<object?[]>();
        var names = PciNames.Value;
        Dictionary<string, double>? nvidiaVram = null;

        foreach (string dev in Lx.Dirs("/sys/bus/pci/devices"))
        {
            string slot = Path.GetFileName(dev);
            string? cls = Lx.Read(dev + "/class");
            if (cls is null || !cls.StartsWith("0x03")) continue; // display controllers

            string? vid = Lx.Read(dev + "/vendor"), did = Lx.Read(dev + "/device");
            string vendor, name;
            if (names.TryGetValue(slot, out var n))
            {
                vendor = CleanVendor(n.Vendor);
                var br = Regex.Match(n.Device, @"\[(.+)\]\s*$");
                name = br.Success ? br.Groups[1].Value : n.Device;
            }
            else
            {
                vendor = VendorFromId(vid);
                name = $"PCI device {vid?.Replace("0x", "")}:{did?.Replace("0x", "")}";
            }

            string? drv = Lx.LinkName(dev + "/driver");
            string? drvVersion = drv is null ? null : Lx.Read($"/sys/module/{drv}/version");
            if (drvVersion is null && drv is not null && kernel is not null) drvVersion = $"bundled with kernel {kernel}";

            // Don't wake a sleeping hybrid-graphics dGPU just to read its memory size.
            bool asleep = Lx.Read(dev + "/power/runtime_status") == "suspended";
            double? vram = null;
            if (!asleep)
            {
                if (Lx.ReadLong(dev + "/mem_info_vram_total") is > 0 and var amdBytes)
                    vram = amdBytes;
                else if (vid?.Equals("0x10de", StringComparison.OrdinalIgnoreCase) == true && drv == "nvidia")
                {
                    nvidiaVram ??= ReadNvidiaVram();
                    string tail = slot.Length >= 7 ? slot[^7..] : slot;
                    foreach (var kv in nvidiaVram)
                        if (kv.Key.EndsWith(tail, StringComparison.OrdinalIgnoreCase)) vram = kv.Value;
                }
            }

            rows.Add(new object?[] { name, vendor, drv, drvVersion, vram is > 0 ? Fmt.Size(vram) : "-" });
        }

        // Non-PCI GPUs (Raspberry Pi, Rockchip, Apple Silicon ...) only exist as DRM devices.
        foreach (string card in Lx.Dirs("/sys/class/drm", "card*"))
        {
            if (!Regex.IsMatch(Path.GetFileName(card), @"^card\d+$")) continue;
            string? real = Lx.RealPath(card + "/device");
            if (real is null || real.Contains("/pci")) continue;
            string? drv = Lx.LinkName(card + "/device/driver");
            if (drv is null) continue;
            rows.Add(new object?[] { $"{drv} (DRM device)", "-", drv, "-", "-" });
        }
        return rows;
    }

    private static Dictionary<string, double> ReadNvidiaVram()
    {
        var d = new Dictionary<string, double>(StringComparer.OrdinalIgnoreCase);
        string? o = Lx.Run("nvidia-smi", new[] { "--query-gpu=pci.bus_id,memory.total", "--format=csv,noheader,nounits" }, 6000);
        if (o is null) return d;
        foreach (string line in o.Split('\n'))
        {
            var p = line.Split(',');
            if (p.Length >= 2 && double.TryParse(p[1].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out double mib))
                d[p[0].Trim()] = mib * 1024 * 1024;
        }
        return d;
    }

    // ------------------------------------------------------------------------------------------
    //  Displays (EDID)
    // ------------------------------------------------------------------------------------------
    private static List<object?[]> ReadDisplays()
    {
        var rows = new List<object?[]>();
        foreach (string dir in Lx.Dirs("/sys/class/drm", "card*-*"))
        {
            if (Lx.Read(dir + "/status") != "connected") continue;
            byte[]? edid = ReadBytes(dir + "/edid");
            if (edid is null || edid.Length < 128) continue;
            if (!(edid[0] == 0 && edid[1] == 0xFF && edid[7] == 0)) continue; // EDID header

            string connector = Regex.Replace(Path.GetFileName(dir), @"^card\d+-", "");

            int mfg = (edid[8] << 8) | edid[9];
            string maker = new string(new[]
            {
                (char)('A' - 1 + ((mfg >> 10) & 0x1F)),
                (char)('A' - 1 + ((mfg >> 5) & 0x1F)),
                (char)('A' - 1 + (mfg & 0x1F))
            });

            int productCode = edid[10] | (edid[11] << 8);
            int week = edid[16], year = edid[17] + 1990;
            string made = (week is 0 or 0xFF ? "-" : week.ToString(CultureInfo.InvariantCulture)) + " / " + year.ToString(CultureInfo.InvariantCulture);

            string? model = null;
            for (int o = 54; o <= 108; o += 18)
            {
                if (edid[o] == 0 && edid[o + 1] == 0 && edid[o + 2] == 0 && edid[o + 3] == 0xFC) // monitor name descriptor
                {
                    model = Encoding.ASCII.GetString(edid, o + 5, 13).Split('\n')[0].Trim();
                    break;
                }
            }

            string native = "-";
            int pixelClock10kHz = edid[54] | (edid[55] << 8);
            if (pixelClock10kHz > 0)
            {
                int hActive = edid[56] | ((edid[58] & 0xF0) << 4);
                int hBlank = edid[57] | ((edid[58] & 0x0F) << 8);
                int vActive = edid[59] | ((edid[61] & 0xF0) << 4);
                int vBlank = edid[60] | ((edid[61] & 0x0F) << 8);
                double total = (double)(hActive + hBlank) * (vActive + vBlank);
                string hz = total > 0 ? $" @ {Math.Round(pixelClock10kHz * 10000.0 / total)} Hz" : "";
                native = $"{hActive} x {vActive}{hz}";
            }

            string size = "-";
            if (edid[21] > 0 && edid[22] > 0)
            {
                double diag = Math.Sqrt(edid[21] * edid[21] + edid[22] * edid[22]) / 2.54;
                size = $"{Fmt.Num(diag, "N1")} in";
            }

            rows.Add(new object?[] { connector, maker, model, productCode.ToString("X4", CultureInfo.InvariantCulture), made, native, size });
        }
        return rows;

        static byte[]? ReadBytes(string path)
        {
            try { return File.Exists(path) ? File.ReadAllBytes(path) : null; }
            catch { return null; }
        }
    }

    // ------------------------------------------------------------------------------------------
    //  Network
    // ------------------------------------------------------------------------------------------
    private static List<object?[]> ReadNetworkAdapters()
    {
        var rows = new List<object?[]>();
        NetworkInterface[] nics;
        try { nics = NetworkInterface.GetAllNetworkInterfaces(); }
        catch { return rows; }

        var names = PciNames.Value;
        foreach (var ni in nics.Where(n => n.NetworkInterfaceType != NetworkInterfaceType.Loopback).OrderBy(n => n.Name, StringComparer.Ordinal))
        {
            string basePath = "/sys/class/net/" + ni.Name;
            string? real = Lx.RealPath(basePath);
            bool virt = real is null || real.Contains("/devices/virtual/");

            string? desc = null;
            if (!virt && Lx.RealPath(basePath + "/device") is { } devReal)
            {
                if (names.TryGetValue(Path.GetFileName(devReal), out var n))
                    desc = $"{CleanVendor(n.Vendor)} {n.Device}";
                else // USB NICs: the product string lives on the USB device, one level above the interface
                {
                    foreach (string up in new[] { devReal, Path.GetDirectoryName(devReal) ?? devReal })
                    {
                        string? prod = Lx.Read(up + "/product");
                        if (prod is null) continue;
                        string? maker = Lx.Read(up + "/manufacturer");
                        desc = maker is not null && !prod.Contains(maker, StringComparison.OrdinalIgnoreCase) ? $"{maker} {prod}" : prod;
                        break;
                    }
                }
            }

            string type = ni.NetworkInterfaceType switch
            {
                NetworkInterfaceType.Ethernet or NetworkInterfaceType.GigabitEthernet or NetworkInterfaceType.FastEthernetT => "Ethernet",
                NetworkInterfaceType.Wireless80211 => "Wi-Fi",
                NetworkInterfaceType.Tunnel => "Tunnel",
                var other => other.ToString()
            };

            string status = ni.OperationalStatus switch
            {
                OperationalStatus.Up => "Up",
                OperationalStatus.Down => "Disconnected",
                OperationalStatus.Testing => "Testing",
                OperationalStatus.Dormant => "Dormant",
                OperationalStatus.NotPresent => "Not Present",
                OperationalStatus.LowerLayerDown => "Lower Layer Down",
                _ => "Unknown"
            };

            // sysfs reports Mb/s, with -1 (or 0xFFFFFFFF on some virtual NICs) meaning "unknown" (always the case for Wi-Fi).
            double? speed = null;
            if (Lx.ReadLong(basePath + "/speed") is > 0 and < 1_000_000 and var mbps) speed = mbps * 1_000_000.0;

            rows.Add(new object?[]
            {
                desc is null ? ni.Name : $"{desc} ({ni.Name})",
                type, status, Fmt.LinkSpeed(speed),
                Lx.LinkName(basePath + "/device/driver") ?? "-",
                Tf(virt)
            });
        }
        return rows;
    }

