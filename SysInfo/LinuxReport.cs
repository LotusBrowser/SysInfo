    private static readonly Lazy<Dictionary<string, (string Vendor, string Device)>> PciNames = new(() =>
    {
        var d = new Dictionary<string, (string, string)>(StringComparer.OrdinalIgnoreCase);
        string? o = Lx.Run("lspci", new[] { "-mm", "-D" }, 5000);
        if (o is null) return d;
        foreach (string line in o.Split('\n'))
        {
            // 0000:00:02.0 "VGA compatible controller" "Intel Corporation" "Alder Lake-P GT2 [Iris Xe Graphics]" -r0c ...
            var m = Regex.Match(line, "^(\\S+)\\s+\"[^\"]*\"\\s+\"([^\"]*)\"\\s+\"([^\"]*)\"");
            if (m.Success) d[m.Groups[1].Value] = (m.Groups[2].Value, m.Groups[3].Value);
        }
        return d;
    });

    private static string CleanVendor(string v)
    {
        if (v.Contains("Advanced Micro Devices", StringComparison.OrdinalIgnoreCase) || v.Contains("AMD", StringComparison.Ordinal))
            return "AMD";
        return Regex.Replace(v, @"[\s,]*(Corporation|Corp\.?|Inc\.?|Ltd\.?|Co\.|Limited)\s*$", "", RegexOptions.IgnoreCase).Trim();
    }

