    // cardsText = /proc/asound/cards, codecDumps(cardId) = contents of that card's codec#N files
    private static List<object?[]> ParseAudio(string? cardsText, Func<string, IEnumerable<string>> codecDumps)
    {
        var rows = new List<object?[]>();
        if (cardsText is null) return rows;

        foreach (string line in cardsText.Split('\n'))
        {
            //  0 [PCH            ]: HDA-Intel - HDA Intel PCH
            var m = Regex.Match(line, @"^\s*(\d+)\s+\[[^\]]*\]:\s*(\S+)\s+-\s+(.+)$");
            if (!m.Success) continue;

            var codecs = new List<string>();
            foreach (string dump in codecDumps(m.Groups[1].Value))
            {
                var cm = Regex.Match(dump, @"^Codec:\s*(.+)$", RegexOptions.Multiline);
                if (cm.Success) codecs.Add(cm.Groups[1].Value.Trim());
            }
            rows.Add(new object?[] { m.Groups[3].Value.Trim(), m.Groups[2].Value, string.Join(", ", codecs.Distinct()) });
        }
        return rows;
    }

