    private static List<object?[]> ReadInputDevices() =>
        ParseInputDevices(Lx.Read("/proc/bus/input/devices"), minor => Lx.Read($"/run/udev/data/c13:{minor}"));

    // text = /proc/bus/input/devices, udevData(minor) = /run/udev/data/c13:<minor> (null if udev has no entry)
    private static List<object?[]> ParseInputDevices(string? text, Func<int, string?> udevData)
    {
        var rows = new List<object?[]>();
        if (text is null) return rows;

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (string block in Regex.Split(text.Replace("\r", ""), @"\n\s*\n"))
        {
            string? name = Regex.Match(block, "^N: Name=\"(.*)\"$", RegexOptions.Multiline) is { Success: true } nm ? nm.Groups[1].Value : null;
            string handlers = Regex.Match(block, @"^H: Handlers=(.*)$", RegexOptions.Multiline) is { Success: true } hm ? hm.Groups[1].Value : "";
            if (string.IsNullOrWhiteSpace(name)) continue;

            bool keyboard, pointing, touchscreen = false;

            // udev already classified every input node; use that when available.
            string? udev = null;
            var ev = Regex.Match(handlers, @"event(\d+)");
            if (ev.Success) udev = udevData(64 + int.Parse(ev.Groups[1].Value, CultureInfo.InvariantCulture));

            if (udev is not null)
            {
                keyboard = udev.Contains("ID_INPUT_KEYBOARD=1");
                pointing = udev.Contains("ID_INPUT_MOUSE=1") || udev.Contains("ID_INPUT_TOUCHPAD=1")
                        || udev.Contains("ID_INPUT_POINTINGSTICK=1") || udev.Contains("ID_INPUT_TRACKBALL=1");
                touchscreen = udev.Contains("ID_INPUT_TOUCHSCREEN=1");
            }
            else
            {
                // Fallback heuristic: keyboards advertise key-repeat (EV_REP, bit 20); mice/touchpads get a "mouse" handler.
                var evBits = Regex.Match(block, @"^B: EV=([0-9a-fA-F]+)$", RegexOptions.Multiline);
                bool rep = evBits.Success && (Convert.ToUInt64(evBits.Groups[1].Value, 16) & (1UL << 20)) != 0;
                keyboard = handlers.Contains("kbd") && rep;
                pointing = handlers.Contains("mouse");
            }

            string? type = keyboard ? "Keyboard" : pointing ? "Pointing" : touchscreen ? "Touchscreen" : null;
            if (type is not null && seen.Add(type + "|" + name))
                rows.Add(new object?[] { type, name });
        }
        return rows.OrderBy(r => (string?)r[0], StringComparer.Ordinal).ThenBy(r => (string?)r[1], StringComparer.OrdinalIgnoreCase).ToList();
    }

